export function filterNavByPermission<T extends NavItem>(items: T[], role: Parameters<typeof can>[0]): T[] {
  return items.filter((item) => {
    const match = NAV_PERMISSIONS.find((entry) => item.href === entry.prefix || item.href.startsWith(`${entry.prefix}/`));
    return Boolean(match && match.permissions.some((permission) => can(role, permission)));
  });
}
